function injectedUserLabel(text) {
  const s = String(text || '').trim();
  if (!s) return null;
  // Skill bodies and the output of slash commands are injected user turns too.
  if (/^Base directory for this skill:/i.test(s)) return '⌘ skill';
  if (/^(?:Caveat: The messages below were generated by the user while running local commands|<command-name>|<local-command-stdout>)/i.test(s)) return '⌘ command';
  if (s.startsWith('<')) return '⟐ system';
  if (/^\[Image #/.test(s)) return '⟐ system';
  if (/system-reminder|runtime context|Time sampled while preparing|approval policy changed|environment_context/i.test(s)) return '⟐ system';
  return null;
}

function isInjectedUserText(text) {
  return injectedUserLabel(text) !== null;
}

// Claude Code names who wrote a prompt in `origin.kind` (or `turnOrigin`); the
// value is lower-cased, dashes and spaces turned to underscores, then looked up.
const ORIGIN_NAMES = {
  human: 'person', user: 'person', person: 'person',
  task_notification: 'task_notification',
  peer: 'peer', agent: 'peer', teammate: 'peer',
  sdk: 'sdk',
  scheduled: 'scheduled', schedule: 'scheduled', cron: 'scheduled',
  queued: 'queued',
};

/** Who wrote a prompt entry or attachment: a name above, the raw value when unknown, or null when it says nothing. */
function originOf(e) {
  const o = e && e.origin;
  const raw = o && typeof o === 'object' ? o.kind : o;
  const value = typeof raw === 'string' && raw.trim() ? raw : (e && typeof e.turnOrigin === 'string' ? e.turnOrigin : '');
  const v = value.trim();
  if (!v) return null;
  return ORIGIN_NAMES[v.toLowerCase().replace(/[\s-]+/g, '_')] || v.slice(0, 40);
}

const promptKey = (text) => String(text || '').replace(/\s+/g, ' ').trim();

/**
 * Whether a main-transcript entry opens the turn (true), closes it (false) or
 * says nothing about it (null). Claude Code writes nothing while the model is
 * composing a long reply, so a quiet transcript alone does not mean idle: the
 * turn is open until an assistant entry stops with end_turn.
 */
const CLOSING_REASONS = new Set(['end_turn', 'stop_sequence', 'refusal']);

function turnSignal(e) {
  if (!e || e.isSidechain || e.isMeta) return null;
  if (e.type === 'assistant') {
    const reason = e.message && e.message.stop_reason;
    if (!reason) return null;
    // Claude Code repeats the reply's final stop_reason on every content-block
    // line; a reply never ends on its thinking, so a thinking-only line says nothing.
    const content = e.message && e.message.content;
    if (Array.isArray(content) && content.length && content.every((b) => b && (b.type === 'thinking' || b.type === 'redacted_thinking'))) return null;
    return !CLOSING_REASONS.has(reason);
  }
  if (e.type !== 'user') return null;
  const content = e.message && e.message.content;
  const blocks = Array.isArray(content) ? content : [{ type: 'text', text: content }];
  if (blocks.some((b) => b && b.type === 'tool_result')) return true;
  const texts = blocks.filter((b) => b && b.type === 'text' && typeof b.text === 'string').map((b) => b.text.trim());
  if (texts.some((t) => /^\[Request interrupted/.test(t))) return false;
  return texts.some((t) => t && !isInjectedUserText(t)) ? true : null;
}

function isToolResultEntry(e) {
  const content = e.message && e.message.content;
  return Array.isArray(content) && content.some((b) => b && b.type === 'tool_result');
}

function mapUsage(u) {
  if (!u) return null;
  return {
    input: u.input_tokens || 0,
    output: u.output_tokens || 0,
    cacheRead: u.cache_read_input_tokens || 0,
    cacheWrite: u.cache_creation_input_tokens || 0,
  };
}

function textOf(content) {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return '';
  return content
    .filter((b) => b && b.type === 'text' && typeof b.text === 'string')
    .map((b) => b.text)
    .join('\n');
}

async function readChunk(file, start, length) {
  const fh = await fsp.open(file, 'r');
  try {
    const buf = Buffer.alloc(length);
    const { bytesRead } = await fh.read(buf, 0, length, start);
    return buf.subarray(0, bytesRead).toString('utf8');
  } finally {
    await fh.close().catch(() => {});
  }
}

async function readMeta(file, st) {
  // Transcripts grow while the agent works, so the cache follows the size.
  const cached = metaCache.get(file);
  if (cached && cached.size === st.size) return cached.meta;
  // Titles and agent names are often appended at the end of long transcripts,
  // so scan the head for cwd/createdAt and the tail for titles as well.
  let headText = '';
  let tailText = '';
  try {
    headText = await readChunk(file, 0, Math.min(st.size, 256 * 1024));
    if (st.size > 256 * 1024) {
      const start = Math.max(0, st.size - 256 * 1024);
      tailText = await readChunk(file, start, st.size - start);
      const nl = tailText.indexOf('\n');
      tailText = nl >= 0 ? tailText.slice(nl + 1) : tailText;
    }
  } catch {
    /* ignore */
  }
  let cwd = null;
  let customTitle = null;
  let agentName = null;
  let lastPrompt = null;
  let firstUser = null;
  let createdAt = null;
  let lastEventAt = 0;
  let sessionId = path.basename(file, '.jsonl');
  const uses = new Set();
  const results = new Set();
  let lastTool = null;
  let turnOpen = false;
  let model = null;
  const touched = new Map();
  // Tool calls by id (for the name of the one still open) and unanswered
  // questions: AskUserQuestion / ExitPlanMode wait for a person.
  const useInfo = new Map();
  const questions = new Map();

  const scan = (text, inTail = false) => {
    for (const line of text.split('\n')) {
      if (!line.trim()) continue;
      let e;
      try { e = JSON.parse(line); } catch { continue; }
      const ts = e.timestamp ? Date.parse(e.timestamp) : 0;
      if (ts) lastEventAt = Math.max(lastEventAt, ts);
      if (!cwd && typeof e.cwd === 'string') cwd = e.cwd;
      if (!createdAt && e.timestamp) createdAt = ts || null;
      if (e.sessionId) sessionId = e.sessionId;
      if (e.type === 'custom-title' && e.customTitle) customTitle = e.customTitle;
      if (e.type === 'agent-name' && e.agentName) agentName = e.agentName;
      if (e.type === 'last-prompt' && e.lastPrompt) lastPrompt = e.lastPrompt;
      if (e.type === 'assistant' && typeof e.message?.model === 'string' && e.message.model !== '<synthetic>') model = e.message.model;
      const signal = turnSignal(e);
      if (signal !== null) turnOpen = signal;
      // A new prompt or an interrupt settles any question that was open.
      if (signal !== null && e.type === 'user' && !isToolResultEntry(e)) questions.clear();
      if (Array.isArray(e.message?.content)) {
        for (const b of e.message.content) {
          if (b?.type === 'tool_use' && b.id) {
            uses.add(b.id);
            if (!e.isSidechain && typeof b.name === 'string') {
              useInfo.set(b.id, { name: b.name, at: ts || lastEventAt });
              if (attention.QUESTION_TOOLS.has(b.name)) questions.set(b.id, { name: b.name, at: ts || lastEventAt, inTail });
            }
          }
          if (b?.type === 'tool_use' && b.name) {
            const input = b.input && typeof b.input === 'object' ? b.input : {};
            const target = typeof input.file_path === 'string' ? input.file_path
              : typeof input.notebook_path === 'string' ? input.notebook_path : null;
            const label = typeof input.command === 'string' ? input.command
              : target || (typeof input.pattern === 'string' ? input.pattern : (typeof input.description === 'string' ? input.description : ''));
            lastTool = { name: String(b.name), label: String(label).slice(0, 300), at: ts || lastEventAt };
            if (target && WRITE_TOOLS.has(b.name)) touched.set(target, ts || lastEventAt);
          }
          if (b?.type === 'tool_result' && b.tool_use_id) {
            results.add(b.tool_use_id);
            questions.delete(b.tool_use_id);
          }
        }
      }
      if (!firstUser && e.type === 'user' && typeof e.message?.content === 'string') {
        const text2 = e.message.content.trim();
        if (text2 && !text2.startsWith('<')) firstUser = text2;
      }
    }
  };
  scan(headText);
  scan(tailText, true);
  // On a long transcript the middle is not read, so only a question seen in
  // the tail can be trusted to be unanswered.
  let question = null;
  for (const q of questions.values()) {
    if (tailText && !q.inTail) continue;
    if (!question || q.at >= question.at) question = { name: q.name, at: q.at };
  }
  let openTool = null;
  for (const [id, use] of useInfo) if (!results.has(id)) openTool = use;

  // The session folder holds the canonical title and the subagent list.
  const folder = path.join(path.dirname(file), path.basename(file, '.jsonl'));
  let subagents = 0;
  try {
    const titleFile = path.join(folder, 'custom-title.json');
    if (fs.existsSync(titleFile)) {
      const t = JSON.parse(fs.readFileSync(titleFile, 'utf8'));
      if (t && typeof t.customTitle === 'string' && t.customTitle.trim()) customTitle = t.customTitle.trim();
    }
  } catch { /* ignore */ }
  try {
    subagents = fs.readdirSync(path.join(folder, 'subagents')).filter((f) => f.endsWith('.jsonl')).length;
  } catch { /* no subagents */ }

  const title = customTitle || agentName || lastPrompt || firstUser || path.basename(file, '.jsonl');
  const meta = {
    id: sessionId,
    cwd: cwd || null,
    title: String(title).replace(/\s+/g, ' ').slice(0, 120),
    createdAt: createdAt || st.birthtimeMs || st.mtimeMs,
    lastEventAt: lastEventAt || st.mtimeMs,
    pending: [...uses].filter((id) => !results.has(id)).length,
    openTool,
    question,
    turnOpen,
    model,
    lastTool,
    touched: [...touched.entries()].sort((a, b) => b[1] - a[1]).slice(0, 50).map(([p, at]) => ({ path: p, at })),
    subagents,
    firstUser: firstUser ? String(firstUser).replace(/\s+/g, ' ').slice(0, 400) : null,
  };
  metaCache.set(file, { size: st.size, meta });
  return meta;
}

async function listSessions(ctx) {
  const root = PROJECTS_ROOT();
  let projects = [];
  try {
    projects = await fsp.readdir(root, { withFileTypes: true });
  } catch {
    return [];
  }
  const found = [];
  for (const project of projects) {
    if (!project.isDirectory()) continue;
    const dir = path.join(root, project.name);
    let files = [];
    try {
      files = await fsp.readdir(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const f of files) {
      if (!f.isFile() || !f.name.endsWith('.jsonl')) continue;
      const file = path.join(dir, f.name);
      let st;
      try { st = await fsp.stat(file); } catch { continue; }
      found.push({ file, project: project.name, size: st.size, mtimeMs: st.mtimeMs, birthtimeMs: st.birthtimeMs });
    }
  }
  found.sort((a, b) => b.mtimeMs - a.mtimeMs);
  const out = [];
  // Claude Code's own status files (busy / idle / waiting), by session id.
  let statuses = new Map();
  try { statuses = await readStatuses(); } catch { /* no status signal */ }
  for (const rec of found.slice(0, 60)) {
    const meta = await readMeta(rec.file, rec);
    const status = statuses.get(meta.id) || null;
    const growth = claudeGrowth.get(rec.file);
    const grew = !!growth && rec.size !== growth.size;
    claudeGrowth.set(rec.file, { size: rec.size, at: grew ? Date.now() : (growth?.at || 0) });
    const lastGrowth = claudeGrowth.get(rec.file).at;
    const now = Date.now();
    const working = meta.turnOpen && now - (meta.lastEventAt || rec.mtimeMs) < OPEN_TURN_MS;
    const lastAt = meta.lastEventAt || rec.mtimeMs;
    // A live process says whether it is working; the transcript only guesses.
    const rawState = status
      ? (status.status === 'idle' ? (now - lastAt < IDLE_MS ? 'idle' : 'finished') : 'live')
      : meta.pending > 0 || now - lastGrowth < 60_000 || working
        ? 'live'
        : now - lastAt < IDLE_MS ? 'idle' : 'finished';
    const state = claudeTracker.update(`claude:${meta.id}`, rawState);
    const last = meta.lastEventAt ? `${ago(now - meta.lastEventAt)} ago` : 'no events yet';
    const statusDetail = !status ? null
      : status.status === 'waiting' ? 'waiting for you'
        : status.status === 'busy' ? `working, last event ${last}`
          : rawState === 'idle' ? `idle since ${last}` : `last event ${last}`;
    const stateDetail = statusDetail || (meta.pending > 0
      ? `open tool call, last event ${last}`
      : working && now - lastGrowth >= 60_000
        ? `working on a reply, last event ${last}`
        : rawState === 'live'
        ? `receiving output, last event ${last}`
        : rawState === 'idle'
          ? `idle since ${last}`
          : `last event ${last}`);
    out.push({
      source: 'claude',
      id: meta.id,
      file: rec.file,
      project: rec.project,
      cwd: meta.cwd,
      title: meta.title,
      firstUser: meta.firstUser,
      empty: false,
      createdAt: meta.createdAt,
      size: rec.size,
      mtimeMs: rec.mtimeMs,
      lastEventAt: meta.lastEventAt,
      subagents: meta.subagents,
      lastTool: meta.lastTool,
      touched: meta.touched,
      model: meta.model || null,
      provider: meta.model ? 'anthropic' : null,
      state,
      attention: attention.claudeAttention({
        status,
        question: meta.question,
        turnOpen: meta.turnOpen,
        state,
        lastEventAt: lastAt,
        openTool: meta.pending > 0 && meta.openTool ? meta.openTool.name : null,
        now,
      }),
      stateDetail,
      live: state === 'live',
    });
  }
  return out;
}

class ClaudeStream extends BaseStream {
  constructor(session, ctx) {
    super(session, ctx);
    this.files = [];
    this.pending = new Map();
    this.discovered = false;
    this.subDir = path.join(path.dirname(session.file), session.id, 'subagents');
    this.seenReplies = new Set();
    this.model = '';
    this.turnNo = 0;
    this.openTurn = 0;
    this.uses = new Map(); // open main-transcript tool calls: id -> { name, at }
    this.questions = new Map(); // unanswered AskUserQuestion / ExitPlanMode: id -> { name, at }
    this.statusSignal = null; // this session's status file, when its process is alive
    this.queuedPrompts = new Map(); // typed mid-turn (queued_command): prompt -> turn number when queued
    this.promptTurns = new Map(); // shown from a user entry: prompt -> turn number
  }

  async _discover() {
    if (!this.files.some((f) => f.main)) {
      const tail = new JsonlTail(this.session.file);
      // Very large transcripts: read the last 24 MiB instead of tens of MiB of
      // history on first attach. Live lines after that are still streamed.
      const st = await tail.stat();
      if (st && st.size > 24 * 1024 * 1024) tail.offset = st.size - 24 * 1024 * 1024;
      this.files.push({ file: this.session.file, tail, main: true, key: 'main' });
    }
    let subs = [];
    try {
      subs = await fsp.readdir(this.subDir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const s of subs) {
      if (!s.isFile() || !s.name.endsWith('.jsonl')) continue;
      const file = path.join(this.subDir, s.name);
      if (this.files.some((f) => f.file === file)) continue;
      this.files.push({
        file,
        tail: new JsonlTail(file, { onObject: (e) => this.processEntry(e, s.name.replace(/\.jsonl$/, '')) }),
        key: s.name.replace(/\.jsonl$/, ''),
      });
    }
  }

  async _poll() {
    await this._discover();
    try {
      this.statusSignal = (await readStatuses()).get(this.session.id) || null;
    } catch {
      this.statusSignal = null;
    }
    let latest = this.lastWriteAt;
    for (const f of this.files) {
      const st = await f.tail.stat();
      if (!st) continue;
      latest = Math.max(latest, st.mtimeMs);
      if (st.size > f.tail.offset) {
        this.markGrowth();
        if (f.main) {
          f.tail.onObject = (e) => this.processEntry(e, null);
          await f.tail.readNew();
        } else {
          await f.tail.readNew();
        }
      } else if (f.main) {
        f.tail.onObject = (e) => this.processEntry(e, null);
      }
    }
    this.lastWriteAt = latest;
    this.emitStatus();
  }

  hasPending() {
    return this.pending.size > 0;
  }

  /** Busy / idle / waiting from the status file beats guessing from the transcript. */
  forcedState(now = Date.now()) {
    const st = this.statusSignal;
    if (!st) return null;
    const last = this.lastEventAt ? `${ago(now - this.lastEventAt)} ago` : 'no events yet';
    if (st.status === 'idle') {
      return now - (this.lastEventAt || 0) < IDLE_MS
        ? { state: 'idle', detail: `idle since ${last}` }
        : { state: 'finished', detail: `last event ${last}` };
    }
    return { state: 'live', detail: st.status === 'waiting' ? 'waiting for you' : `working, last event ${last}` };
  }

  attentionNow(s = { state: this.live ? 'live' : 'finished' }) {
    let question = null;
    for (const q of this.questions.values()) if (!question || q.at >= question.at) question = q;
    let openTool = null;
    for (const use of this.uses.values()) openTool = use;
    return attention.claudeAttention({
      status: this.statusSignal,
      question,
      turnOpen: this.turnOpen,
      state: s.state,
      lastEventAt: this.lastEventAt,
      openTool: openTool ? openTool.name : null,
      now: Date.now(),
    });
  }

  /** Track the open tool calls and questions of the main transcript. */
  noteUse(block, ts) {
    if (!block.id || typeof block.name !== 'string') return;
    this.uses.set(block.id, { name: block.name, at: ts });
    if (this.uses.size > 300) this.uses.delete(this.uses.keys().next().value);
    if (attention.QUESTION_TOOLS.has(block.name)) this.questions.set(block.id, { name: block.name, at: ts });
  }

  processEntry(e, agent) {
    const ts = Date.parse(e.timestamp) || Date.now();
    if (e.type === 'attachment') return this.queuedPrompt(e, agent, ts);
    let endsTurn = false;
    // A prompt that was typed mid-turn is shown from its queued_command attachment;
    // the user entry that repeats it adds nothing and joins the running turn.
    let duplicate = false;
    if (!agent && e.type === 'user' && !isToolResultEntry(e)) {
      const key = promptKey(textOf(e.message?.content));
      if (key && this.queuedPrompts.get(key) === this.turnNo) {
        this.queuedPrompts.delete(key);
        duplicate = true;
      }
    }
    if (!agent) {
      const signal = turnSignal(e);
      if (signal !== null) this.turnOpen = signal;
      if (signal !== null && e.type === 'user' && !isToolResultEntry(e)) this.questions.clear();
      // A real prompt opens a turn; end_turn or an interrupt closes it.
      if (signal === true && e.type === 'user' && !isToolResultEntry(e)) {
        if (!(duplicate && this.openTurn)) {
          this.closeTurn(ts);
          this.turnNo += 1;
          this.openTurn = this.turnNo;
          this.add({ t: 'turn', turn: this.turnNo, time: ts });
        }
      } else if (signal === false) {
        endsTurn = true;
      }
    }
    const turn = this.openTurn || undefined;
    if (e.type === 'assistant') {
      // Claude Code writes one line per content block and repeats the reply's
      // usage on each, so a reply is one step and its usage counts once.
      const msgId = e.message?.id;
      const first = !msgId || !this.seenReplies.has(msgId);
      if (msgId && first) {
        this.seenReplies.add(msgId);
        if (this.seenReplies.size > 20000) this.seenReplies = new Set([...this.seenReplies].slice(-10000));
      }
      if (first) this.add({ t: 'step', turn, time: ts, agent });
      const content = e.message?.content;
      const model = typeof e.message?.model === 'string' ? e.message.model : '';
      if (model && model !== '<synthetic>' && !agent) this.model = model;
      const usage = first ? mapUsage(e.message?.usage) : null;
      const cost = usage ? claudeCost(model, e.message.usage) : null;
      const texts = [];
      const toolBlocks = [];
      let thinking = '';
      for (const b of Array.isArray(content) ? content : []) {
        if (b.type === 'text' && typeof b.text === 'string' && b.text.trim()) texts.push(b.text);
        else if ((b.type === 'thinking' || b.type === 'redacted_thinking') && typeof b.thinking === 'string' && b.thinking.trim()) {
          thinking += (thinking ? '\n\n' : '') + b.thinking;
        } else if (b.type === 'tool_use') {
          toolBlocks.push(b);
        }
      }
      const text = texts.join('\n');
      if (text || thinking || usage) {
        this.add({
          t: 'say',
          text,
          thinking: thinking ? thinking.slice(0, 20000) : undefined,
          usage,
          ...(usage ? { model: model || undefined, cost: cost ?? undefined } : {}),
          turn,
          time: ts,
          agent,
        });
      }
      for (const b of toolBlocks) {
        if (!agent) this.noteUse(b, ts);
        this.toolCall(b, e, agent, ts);
      }
      if (endsTurn) this.closeTurn(ts);
      return;
    }
    if (endsTurn) this.closeTurn(ts);
    if (e.type === 'user') {
      const content = e.message?.content;
      const origin = originOf(e);
      const show = (text) => {
        if (duplicate) return;
        const systemLabel = injectedUserLabel(text);
        if (!agent) this.remember(this.promptTurns, promptKey(text));
        // Without a stated origin a prompt is the person's, unless it is text Claude Code injected.
        this.add({ t: 'user', text, system: !!systemLabel, systemLabel, origin: origin || (systemLabel ? 'system' : 'person'), turn, time: ts, agent });
      };
      if (typeof content === 'string') {
        if (content.trim()) show(content);
        return;
      }
      for (const b of Array.isArray(content) ? content : []) {
        if (b.type === 'tool_result') this.toolResult(b, e, agent, ts);
        else if (b.type === 'text' && typeof b.text === 'string' && b.text.trim()) show(b.text);
      }
    }
  }

  /** Remember a prompt against the turn it belongs to; the list stays short. */
  remember(map, key) {
    if (!key) return;
    map.set(key, this.turnNo);
    if (map.size > 200) map.delete(map.keys().next().value);
  }

  /**
   * A prompt typed while a turn was running. Claude Code writes it as a
   * queued_command attachment, and only sometimes also as a user entry, so the
   * attachment is the one place every such prompt appears. It joins the running
   * turn and never opens one.
   */
  queuedPrompt(e, agent, ts) {
    const a = e.attachment;
    if (!a || a.type !== 'queued_command') return;
    const text = typeof a.prompt === 'string' ? a.prompt : textOf(a.prompt);
    const key = promptKey(text);
    if (!key) return;
    if (!agent) {
      if (this.promptTurns.get(key) === this.turnNo) return; // the user entry already showed it
      this.remember(this.queuedPrompts, key);
    }
    const stated = originOf(a);
    const systemLabel = injectedUserLabel(text);
    this.add({
      t: 'user', text, system: !!systemLabel, systemLabel,
      origin: !stated || stated === 'person' ? 'queued' : stated,
      turn: this.openTurn || undefined, time: ts, agent,
    });
  }

  closeTurn(ts, reason) {
    if (!this.openTurn) return;
    this.add({ t: 'turnEnd', turn: this.openTurn, time: ts, ...(reason ? { reason } : {}) });
    this.openTurn = 0;
  }

  toolCall(block, entry, agent, ts) {
    const name = TOOL_MAP[block.name];
    if (!name) return;
    const input = block.input || {};
    const args = {};
    let ref = null;
    if (name === 'pwsh') {
      args.command = String(input.command || '');
      args.description = input.description ? String(input.description) : '';
      args.workdir = entry.cwd || this.session.cwd || '';
    } else {
      ref = this.fileRef(input.file_path);
      if (ref) {
        args.file_path = ref.path;
        args.key = ref.key;
      }
      if (name === 'edit') {
        args.old_string = String(input.old_string ?? '');
        args.new_string = String(input.new_string ?? '');
      } else if (name === 'write') {
        args.content = String(input.content ?? '');
      }
    }
    this.pending.set(block.id, {
      name,
      args,
      display: args.file_path,
      key: args.key,
      command: args.command,
      cwd: entry.cwd || this.session.cwd,
    });
    this.add({ t: 'call', callId: block.id, name, args, time: ts, agent });
  }

  toolResult(block, entry, agent, ts) {
    if (!agent) {
      this.uses.delete(block.tool_use_id);
      this.questions.delete(block.tool_use_id);
    }
    const pending = this.pending.get(block.tool_use_id);
    if (pending) this.pending.delete(block.tool_use_id);
    let text = textOf(block.content);
    const tr = entry.toolUseResult;
    if (!text) {
      if (typeof tr === 'string') text = tr;
      else if (Array.isArray(tr)) text = textOf(tr);
      else if (tr && typeof tr === 'object') text = [tr.stdout, tr.stderr].filter(Boolean).join('\n');
    }
    const isError = !!block.is_error || !!(tr && tr.interrupted);
    this.add({
      t: 'result',
      callId: block.tool_use_id,
      text,
      isError,
      meta: pending && pending.display ? { path: pending.display, key: pending.key } : null,
      time: ts,
      agent,
    });
    if (!isError && pending && pending.command) {
      for (const abs of deletionsFromCommand(pending.command, pending.cwd)) {
        const display = this.displayPath(abs) || abs;
        this.addDeleted(display, ts);
      }
    }
  }
}

function open(record, ctx) {
  return new ClaudeStream(record, ctx);
}

